const {test, after}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const {execFileSync}=require('node:child_process');
const root=path.resolve(__dirname,'../..');
const source=path.join(root,'src/lib/teamAccountSetup.ts');
const out=fs.mkdtempSync(path.join(os.tmpdir(),'hq-team-contract-'));
execFileSync(path.join(root,'node_modules/.bin/tsc'),[source,'--outDir',out,'--strict','--target','ES2022','--module','commonjs','--skipLibCheck'],{stdio:'pipe'});
const {createdUserId,workspaceRoleFor,permissionEnabled,checkedSetupWrite}=require(path.join(out,'teamAccountSetup.js'));
after(()=>fs.rmSync(out,{recursive:true,force:true}));
const id='11111111-2222-3333-4444-555555555555', other='aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee';
test('server nested user ID is read',()=>assert.equal(createdUserId({success:true,user:{id}}),id));
test('legacy user_id works',()=>assert.equal(createdUserId({user_id:id}),id));
test('legacy top-level ID works',()=>assert.equal(createdUserId({id}),id));
test('matching aliases work',()=>assert.equal(createdUserId({id,user_id:id,user:{id}}),id));
test('aliases are case insensitive',()=>assert.equal(createdUserId({user_id:other,user:{id:other.toUpperCase()}}),other));
test('missing ID is rejected',()=>assert.throws(()=>createdUserId({success:true}),/valid user ID/));
test('conflicting IDs are rejected',()=>assert.throws(()=>createdUserId({user_id:id,user:{id:other}}),/conflicting/));
test('malformed ID is rejected',()=>assert.throws(()=>createdUserId({user:{id:'nope'}}),/valid user ID/));
test('provider error is rejected',()=>assert.throws(()=>createdUserId({user_id:id,error:'failed'}),/not confirmed/));
test('failed response is rejected',()=>assert.throws(()=>createdUserId({user_id:id,success:false}),/not confirmed/));
test('null response is rejected',()=>assert.throws(()=>createdUserId(null),/not confirmed/));
for(const [role,expected] of Object.entries({admin:'owner',owner:'owner',gm:'gm',manager:'gm',shift_lead:'lead',staff:'foh',client:'client'})) {
  test(role+' workspace role mapping',()=>assert.equal(workspaceRoleFor(role),expected));
}
test('unknown roles denied',()=>assert.throws(()=>workspaceRoleFor('super_admin'),/Unknown/));
test('prototype property not a role',()=>assert.throws(()=>workspaceRoleFor('toString'),/Unknown/));
test('only explicit true enables',()=>assert.equal(permissionEnabled({a:true},'a'),true));
test('missing settings disabled',()=>assert.equal(permissionEnabled({},'a'),false));
test('false disables',()=>assert.equal(permissionEnabled({a:false},'a'),false));
test('truthy text not a permission',()=>assert.equal(permissionEnabled({a:'true'},'a'),false));
test('inherited setting not trusted',()=>assert.equal(permissionEnabled(Object.create({a:true}),'a'),false));
test('successful write resolves',async()=>await checkedSetupWrite(Promise.resolve({error:null}),'Assignments'));
test('database error rejects',async()=>assert.rejects(checkedSetupWrite(Promise.resolve({error:{message:'denied'}}),'Assignments'),/Assignments: denied/));
test('unknown error rejects',async()=>assert.rejects(checkedSetupWrite(Promise.resolve({error:true}),'Assignments'),/could not save/));
test('network failure rejects',async()=>assert.rejects(checkedSetupWrite(Promise.reject(new Error('offline')),'Assignments'),/offline/));
const create=fs.readFileSync(path.join(root,'src/components/admin/CreateUserDialog.tsx'),'utf8');
const perms=fs.readFileSync(path.join(root,'src/components/admin/RolePageDefaults.tsx'),'utf8');
test('creation validates returned server ID',()=>assert.match(create,/const newUserId = createdUserId\(data\)/));
test('project assignment uses unique-key upsert',()=>assert.match(create,/\.upsert\(barAssignRows, \{ onConflict: 'user_id,bar_id' \}\)/));
test('duplicate submissions blocked',()=>assert.match(create,/if \(creatingRef.current\) return/));
test('incomplete setup has a recovery message',()=>assert.match(create,/account exists, but setup is incomplete/));
test('lookup failures block permission saves',()=>assert.match(perms,/if \(isLoading \|\| loadError \|\| isSaving\) return/));
test('no implicit enabled fallback',()=>assert.doesNotMatch(perms,/\?\? true/));
